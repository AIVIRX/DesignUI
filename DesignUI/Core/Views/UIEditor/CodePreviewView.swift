import SwiftUI
import HighlightSwift

struct CodePreviewView: View {
    @ObservedObject var canvasManager: CanvasManager
    @Environment(\.dismiss) private var dismiss
    @Environment(\.colorScheme) private var colorScheme
    
    var body: some View {
        NavigationStack {
            VStack(spacing: 0) {
                // Header with styling matching CodeSnippets
                HStack {
                    Text("Generated Code")
                        .font(.system(size: 14, weight: .semibold))
                        .foregroundColor(.primary)
                    
                    Spacer()
                    
                    Button(action: {
                        copyToClipboard(completeFileCode)
                    }) {
                        HStack(spacing: 4) {
                            Image(systemName: "doc.on.doc")
                                .font(.system(size: 12, weight: .medium))
                            Text("Copy code")
                                .font(.system(size: 12, weight: .medium))
                        }
                        .foregroundColor(.primary)
                        .padding(.horizontal, 12)
                        .padding(.vertical, 6)
                        .background(
                            RoundedRectangle(cornerRadius: 10)
                                .fill(Color.gray.opacity(0.2))
                        )
                    }
                    .buttonStyle(PlainButtonStyle())
                    
                    Button("Done") {
                        dismiss()
                    }
                    .buttonStyle(.borderedProminent)
                }
                .padding(.horizontal, 16)
                .padding(.vertical, 12)
                .background(
                    Rectangle()
                        .fill(Color.gray.opacity(0.2))
                )
                
                // Code content with syntax highlighting
                ScrollView {
                    VStack(alignment: .leading, spacing: 0) {
                        CompleteFileCode(canvasManager: canvasManager)
                    }
                    .padding(20)
                }
                .background(Color.gray.opacity(0.1))
            }
        }
        .frame(minWidth: 600, minHeight: 500)
        .background(Color.gray.opacity(0.1))
        .cornerRadius(20)
        .overlay(
            RoundedRectangle(cornerRadius: 20)
                .stroke(
                    colorScheme == .dark
                        ? Color(red: 0.3, green: 0.3, blue: 0.3)
                        : Color(red: 0.8, green: 0.8, blue: 0.8),
                    lineWidth: 1
                )
        )
    }
    
    private var completeFileCode: String {
        let viewCode = canvasManager.exportCode()
        return """
        //
        //  GeneratedView.swift
        //  YourApp
        //
        //  Generated by DockUI Studio
        //  Created on \(Date().formatted(date: .abbreviated, time: .shortened))
        //

        \(viewCode)

        """
    }
}

struct CompleteFileCode: View {
    @ObservedObject var canvasManager: CanvasManager
    @Environment(\.colorScheme) private var colorScheme
    @State private var highlightedText: AttributedString = AttributedString()
    @State private var isHighlighting = false
    
    private let highlight = Highlight()
    
    private var completeFileCode: String {
        let viewCode = canvasManager.exportCode()
        return """
        //
        //  GeneratedView.swift
        //  YourApp
        //
        //  Generated by DockUI Studio
        //  Created on \(Date().formatted(date: .abbreviated, time: .shortened))
        //

        \(viewCode)

        """
    }
    
    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            // Code content area with syntax highlighting
            ScrollView(.vertical, showsIndicators: true) {
                Text(highlightedText)
                    .font(.system(size: 14, design: .monospaced))
                    .textSelection(.enabled)
                    .padding()
                    .frame(maxWidth: .infinity, alignment: .leading)
            }
            .frame(maxWidth: .infinity)
            .overlay(loadingOverlay)
        }
        .onAppear {
            generateHighlightedText()
        }
        .onChange(of: completeFileCode) {
            generateHighlightedText()
        }
        .onChange(of: colorScheme) {
            generateHighlightedText()
        }
    }
    
    private var loadingOverlay: some View {
        Group {
            if isHighlighting {
                VStack {
                    Spacer()
                    HStack {
                        #if os(macOS)
                        Color.clear
                            .frame(width: 24, height: 24)
                            .overlay(
                                ProgressView()
                                    .progressViewStyle(CircularProgressViewStyle())
                            )
                        #else
                        ProgressView()
                            .scaleEffect(0.8)
                        #endif
                    }
                    .padding(.horizontal, 16)
                    .padding(.vertical, 8)
                    .background(
                        RoundedRectangle(cornerRadius: 20)
                            .fill(Color.gray.opacity(0.2))
                    )
                    Spacer()
                }
            }
        }
    }
    
    private func performHighlight(_ code: String) async {
        do {
            // Use appropriate theme based on color scheme
            let result = try await highlight.attributedText(
                code,
                language: "swift",
                colors: colorScheme == .dark ? .dark(.xcode) : .light(.github)
            )
            
            await MainActor.run {
                self.highlightedText = result
                self.isHighlighting = false
            }
        } catch {
            // Fallback to plain text with proper color
            await MainActor.run {
                var fallbackText = AttributedString(code)
                fallbackText.font = .system(size: 14, design: .monospaced)
                fallbackText.foregroundColor = colorScheme == .dark 
                    ? Color(red: 0.9, green: 0.9, blue: 0.9)
                    : Color(red: 0.1, green: 0.1, blue: 0.1)
                self.highlightedText = fallbackText
                self.isHighlighting = false
            }
        }
    }
    
    private func generateHighlightedText() {
        // Show loading indicator for large code
        if completeFileCode.count > 1000 {
            isHighlighting = true
        }
        
        // Start highlighting immediately in background
        Task {
            await performHighlight(completeFileCode)
        }
    }
}
