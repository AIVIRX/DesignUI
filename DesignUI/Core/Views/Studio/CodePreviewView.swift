import SwiftUI
#if os(macOS)
struct CodePreviewView: View {
    @ObservedObject var canvasManager: CanvasManager
    @Environment(\.dismiss) private var dismiss
    
    var body: some View {
        NavigationStack {
            VStack(spacing: 0) {
                // Header
                HStack {
                    Text("Generated Code")
                        .font(.headline)
                    
                    Spacer()
                    
                    Button("Done") {
                        dismiss()
                    }
                    .buttonStyle(.borderedProminent)
                }
                .padding(.horizontal, 20)
                .padding(.vertical, 16)
                .background(Color(NSColor.controlBackgroundColor))
                
                Divider()
                
                .pickerStyle(SegmentedPickerStyle())
                .padding(.horizontal, 20)
                .padding(.vertical, 12)
                
                Divider()
                
                // Code content
                ScrollView {
                    VStack(alignment: .leading, spacing: 0) {
                            CompleteFileCode(canvasManager: canvasManager)
                    }
                    .padding(20)
                }
                .background(Color(NSColor.textBackgroundColor))
            }
        }
        .frame(minWidth: 600, minHeight: 500)
    }
}

struct CompleteFileCode: View {
    @ObservedObject var canvasManager: CanvasManager
    
    private var completeFileCode: String {
        let viewCode = canvasManager.exportCode()
        return """
        //
        //  GeneratedView.swift
        //  YourApp
        //
        //  Generated by SwiftUI Builder
        //  Created on \(Date().formatted(date: .abbreviated, time: .shortened))
        //

        import SwiftUI

        struct GeneratedView: View {
            var body: some View {
                \(viewCode)
            }
        }

        #Preview {
            GeneratedView()
                .padding()
        }
        """
    }
    
    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text("// Complete Swift File")
                .font(.caption)
                .foregroundColor(.secondary)
            
            Text(completeFileCode)
                .font(.system(.body, design: .monospaced))
                .textSelection(.enabled)
                .padding(16)
                .background(
                    RoundedRectangle(cornerRadius: 8)
                        .fill(Color(NSColor.controlBackgroundColor))
                )
        }
    }
}
#endif
