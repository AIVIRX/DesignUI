import SwiftUI

struct CodePreviewView: View {
    @ObservedObject var canvasManager: CanvasManager
    @Environment(\.dismiss) private var dismiss
    @State private var selectedTab = 2
    
    var body: some View {
        NavigationView {
            VStack(spacing: 0) {
                // Header
                HStack {
                    Text("Generated Code")
                        .font(.headline)
                    
                    Spacer()
                    
                    Button("Done") {
                        dismiss()
                    }
                    .buttonStyle(.borderedProminent)
                }
                .padding(.horizontal, 20)
                .padding(.vertical, 16)
                .background(Color(NSColor.controlBackgroundColor))
                
                Divider()
                
                // Tab picker
                Picker("View Type", selection: $selectedTab) {
                    Text("SwiftUI View").tag(0)
                    Text("Preview").tag(1)
                    Text("Complete File").tag(2)
                }
                .pickerStyle(SegmentedPickerStyle())
                .padding(.horizontal, 20)
                .padding(.vertical, 12)
                
                Divider()
                
                // Code content
                ScrollView {
                    VStack(alignment: .leading, spacing: 0) {
                        if selectedTab == 0 {
                            SwiftUIViewCode(canvasManager: canvasManager)
                        } else if selectedTab == 1 {
                            PreviewCode(canvasManager: canvasManager)
                        } else {
                            CompleteFileCode(canvasManager: canvasManager)
                        }
                    }
                    .padding(20)
                }
                .background(Color(NSColor.textBackgroundColor))
            }
        }
        .frame(minWidth: 600, minHeight: 500)
    }
}

struct SwiftUIViewCode: View {
    @ObservedObject var canvasManager: CanvasManager
    
    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text("// Generated SwiftUI View")
                .font(.caption)
                .foregroundColor(.secondary)
            
            Text(canvasManager.exportCode())
                .font(.system(.body, design: .monospaced))
                .textSelection(.enabled)
                .padding(16)
                .background(
                    RoundedRectangle(cornerRadius: 8)
                        .fill(Color(NSColor.controlBackgroundColor))
                )
        }
    }
}

struct PreviewCode: View {
    @ObservedObject var canvasManager: CanvasManager
    
    private var previewCode: String {
        let viewCode = canvasManager.exportCode()
        return """
        #Preview {
            GeneratedView()
                .padding()
        }
        """
    }
    
    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text("// SwiftUI Preview")
                .font(.caption)
                .foregroundColor(.secondary)
            
            Text(previewCode)
                .font(.system(.body, design: .monospaced))
                .textSelection(.enabled)
                .padding(16)
                .background(
                    RoundedRectangle(cornerRadius: 8)
                        .fill(Color(NSColor.controlBackgroundColor))
                )
        }
    }
}

struct CompleteFileCode: View {
    @ObservedObject var canvasManager: CanvasManager
    
    private var completeFileCode: String {
        let viewCode = canvasManager.exportCode()
        return """
        //
        //  GeneratedView.swift
        //  YourApp
        //
        //  Generated by SwiftUI Builder
        //

        import SwiftUI

        \(viewCode)

        #Preview {
            GeneratedView()
                .padding()
        }
        """
    }
    
    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text("// Complete Swift File")
                .font(.caption)
                .foregroundColor(.secondary)
            
            Text(completeFileCode)
                .font(.system(.body, design: .monospaced))
                .textSelection(.enabled)
                .padding(16)
                .background(
                    RoundedRectangle(cornerRadius: 8)
                        .fill(Color(NSColor.controlBackgroundColor))
                )
        }
    }
}

#Preview {
    let canvasManager = CanvasManager()
    
    return CodePreviewView(canvasManager: canvasManager)
}
