create table if not exists public.ai_generations (
    id uuid primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    prompt text not null,
    generation_mode text not null,
    generated_screen jsonb not null,
    component_count integer not null default 0,
    created_at timestamptz not null default now()
);

create index if not exists ai_generations_user_created_idx
    on public.ai_generations (user_id, created_at desc);

create table if not exists public.ai_generation_events (
    id bigint generated by default as identity primary key,
    generation_id uuid not null references public.ai_generations(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    event_type text not null check (event_type in ('applied', 'edited', 'regenerated', 'kept', 'undone', 'exported')),
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists ai_generation_events_generation_created_idx
    on public.ai_generation_events (generation_id, created_at);

create index if not exists ai_generation_events_user_created_idx
    on public.ai_generation_events (user_id, created_at desc);

alter table public.ai_generations enable row level security;
alter table public.ai_generation_events enable row level security;

create policy "Users can read their AI generations"
    on public.ai_generations for select
    using (auth.uid() = user_id);

create policy "Users can read their AI generation events"
    on public.ai_generation_events for select
    using (auth.uid() = user_id);
